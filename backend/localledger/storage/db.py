"""Encrypted persistence.

The production path is SQLCipher with a raw 256-bit key held in the macOS Keychain.
A plain-SQLite mode exists ONLY behind ``insecure=True`` (LOCALLEDGER_INSECURE_DEV_DB=1)
for development on machines where SQLCipher is unavailable. It provides no
confidentiality and is never selected automatically.
"""

from __future__ import annotations

import sqlite3
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path
from typing import Any

try:  # pragma: no cover - import guard
    from sqlcipher3 import dbapi2 as _sqlcipher
except ImportError:  # pragma: no cover
    _sqlcipher = None


class StorageError(RuntimeError):
    pass


MIGRATIONS: list[str] = [
    """
    CREATE TABLE accounts (
        id INTEGER PRIMARY KEY,
        name TEXT NOT NULL UNIQUE,
        institution TEXT NOT NULL DEFAULT '',
        type TEXT NOT NULL DEFAULT 'checking',
        currency TEXT NOT NULL DEFAULT 'USD',
        connector TEXT NOT NULL DEFAULT 'csv',
        created_at TEXT NOT NULL DEFAULT (datetime('now'))
    );
    CREATE TABLE imports (
        id INTEGER PRIMARY KEY,
        account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
        filename TEXT NOT NULL,
        file_sha256 TEXT NOT NULL,
        rows_total INTEGER NOT NULL,
        rows_inserted INTEGER NOT NULL,
        rows_duplicate INTEGER NOT NULL,
        rows_invalid INTEGER NOT NULL,
        imported_at TEXT NOT NULL DEFAULT (datetime('now'))
    );
    CREATE TABLE transactions (
        id INTEGER PRIMARY KEY,
        account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
        import_id INTEGER REFERENCES imports(id) ON DELETE SET NULL,
        posted_date TEXT NOT NULL,
        amount_minor INTEGER NOT NULL,
        currency TEXT NOT NULL,
        description_raw TEXT NOT NULL,
        merchant TEXT NOT NULL,
        category TEXT NOT NULL,
        is_pending INTEGER NOT NULL DEFAULT 0,
        is_transfer INTEGER NOT NULL DEFAULT 0,
        fingerprint TEXT NOT NULL UNIQUE,
        created_at TEXT NOT NULL DEFAULT (datetime('now'))
    );
    CREATE INDEX idx_tx_date ON transactions(posted_date);
    CREATE INDEX idx_tx_category ON transactions(category, posted_date);
    CREATE INDEX idx_tx_account ON transactions(account_id, posted_date);
    CREATE TABLE settings (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL
    );
    """,
]


class Database:
    def __init__(self, path: Path, key: bytes | None, *, insecure: bool = False) -> None:
        if insecure:
            self._driver: Any = sqlite3
            self._key_hex = None
        else:
            if _sqlcipher is None:
                raise StorageError(
                    "SQLCipher driver (sqlcipher3) is not installed. Refusing to store "
                    "financial data unencrypted. For development only, set "
                    "LOCALLEDGER_INSECURE_DEV_DB=1."
                )
            if key is None or len(key) != 32:
                raise StorageError("A 32-byte database key is required.")
            self._driver = _sqlcipher
            self._key_hex = key.hex()
        self.path = Path(path)
        self.encrypted = not insecure
        self.path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)

    def _open(self) -> Any:
        conn = self._driver.connect(str(self.path), timeout=10, check_same_thread=False)
        try:
            if self._key_hex is not None:
                # Raw key: skips the passphrase KDF. The hex is generated by us, never user input.
                conn.execute(f"PRAGMA key = \"x'{self._key_hex}'\"")
            conn.execute("PRAGMA foreign_keys = ON")
            conn.execute("PRAGMA journal_mode = WAL")
            conn.execute("SELECT count(*) FROM sqlite_master").fetchone()
        except Exception as exc:
            conn.close()
            raise StorageError("Could not open the database (wrong key or corrupt file).") from exc
        conn.row_factory = self._driver.Row
        return conn

    @contextmanager
    def connect(self) -> Iterator[Any]:
        conn = self._open()
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()

    def migrate(self) -> None:
        with self.connect() as conn:
            version = conn.execute("PRAGMA user_version").fetchone()[0]
            for index in range(version, len(MIGRATIONS)):
                conn.executescript(MIGRATIONS[index])
                conn.execute(f"PRAGMA user_version = {index + 1}")
        if self.path.exists():
            self.path.chmod(0o600)

    def delete_all_data(self) -> None:
        with self.connect() as conn:
            for table in ("transactions", "imports", "accounts", "settings"):
                conn.execute(f"DELETE FROM {table}")  # noqa: S608 - fixed table names
        with self.connect() as conn:
            conn.isolation_level = None
            conn.execute("VACUUM")
